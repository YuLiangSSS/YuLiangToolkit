/// <summary>一条称谓：同一个亲戚的北方叫法、南方叫法、书面称谓与白话解释。</summary>
/// <param name="Key">规范化关系链的紧凑写法（<see cref="KinPath.ToToken"/>），例如 <c>F+oB</c>。</param>
/// <param name="North">北方口语叫法（可能为空：北方没有专门的说法，就沿用通用写法）。</param>
/// <param name="South">南方口语叫法（可能为空）。</param>
/// <param name="Formal">书面称谓（族谱 / 正式书面用，例如「伯父」「姨母」）。</param>
/// <param name="Note">白话解释 / 地区差异说明。</param>
public sealed record KinTerm(
    string Key,
    string North,
    string South,
    string Formal,
    string Note)
{
    /// <summary>两边的叫法都是同一个词时，就是「南北叫法一致」。</summary>
    public bool IsSameNationwide => string.Equals(North, South, StringComparison.Ordinal);
}

