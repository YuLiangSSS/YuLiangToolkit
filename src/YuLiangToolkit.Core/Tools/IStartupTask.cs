namespace YuLiangToolkit.Core.Tools;

/// <summary>
/// 「本程序启动起来之后还想顺手做点事」的工具。
///
/// <para>外壳在**主窗口已经显示、托盘 / 单实例服务端都就绪之后**，会依次问每个已发现的工具
/// （<see cref="ITool"/> 实例本身，不是界面 ViewModel）：要不要在启动时干活，要就调
/// <see cref="RunOnStartup"/> 一次。</para>
///
/// <para><b>为什么要放在工具实例上而不是 ViewModel 上</b>：开机自启时用户要的是「程序起来了，
/// 顺带把我配好的东西也拉起来」，这时候他要的开的程序并不需要工具页被打开过；
/// 而工具页面是懒加载的（切走还会进缓存 / 被淘汰），靠页面生命周期根本保证不了「每次启动都跑一次」。</para>
///
/// <para><b>为什么放在 Core</b>：外壳不能认识具体工具（<c>App</c> 里没有、也不该有对
/// 「软件启动器」的引用）。定个约定，谁需要谁实现。</para>
///
/// <para>⚠ <b>实现要求</b>：这个方法在 UI 线程上被同步调用，必须**立刻返回**——
/// 耗时 / 会弹窗 / 会启动外部进程的事情全部丢到后台去做，别在这里等（否则拖慢整个程序启动）。
/// 另外它不能抛异常（外壳有兜底，但异常会让后面的工具收不到这次机会）。</para>
///
/// <para>⚠ 目前只有「软件启动器」实现它（联动启动）。以后的实现请先想清楚
/// 「用户重启程序（渲染 GPU / 提权重启）时会不会重复触发」——外壳不会替你去重。</para>
/// </summary>
public interface IStartupTask
{
    /// <summary>要不要在这次程序启动时干活（读自己的配置，纯判断、无副作用）。</summary>
    bool ShouldRunOnStartup { get; }

    /// <summary>干一次启动任务（必须立刻返回，耗时工作丢后台）。</summary>
    void RunOnStartup();
}
